export type BriefCopyKey = keyof typeof en;

export function briefCopy(locale: Locale, key: BriefCopyKey, vars?: Record<string, string | number>) {
  const template = (locale === "ar" ? ar : en)[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? "" : String(vars[name]),
  );
}

export const briefCopyKeys = Object.keys(en) as BriefCopyKey[];
