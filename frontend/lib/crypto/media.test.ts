import { describe, expect, it } from "vitest";
import { decryptPhotoBytes, encryptPhotoBytes } from "./media";

function png1x1() {
  return Uint8Array.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
    0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
    0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, 0x89, 0x00, 0x00, 0x00,
    0x0a, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x00, 0x01, 0x00, 0x00,
    0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49,
    0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
  ]);
}

describe("photo encryption", () => {
  it("decrypts ciphertext back to the original bytes", async () => {
    const original = png1x1();
    const encrypted = await encryptPhotoBytes(original, "image/png");
    const blob = await decryptPhotoBytes(
      encrypted.ciphertext,
      encrypted.key,
      encrypted.nonce,
      "image/png",
    );
    expect(new Uint8Array(await blob.arrayBuffer())).toEqual(original);
  });
});
